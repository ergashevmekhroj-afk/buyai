"""Adds the 8 regions that were missing (stat.uz SIAT open data, same tables as the other regions).

Run from data/:  python3 scripts/add_regions.py <folder with sdmx_data_<ID>.json files>
Download each file from https://api.siat.stat.uz/media/uploads/sdmx/sdmx_data_<ID>.json
Writes raw/<ID>_<region>_markets.txt (same format as the other raw files) and out/new_regions.sql.

Rules (same as build.py): prices exactly as published; 0 or empty = not observed = NULL (no zero-filling);
products not in our list of 38 (bran, schroth, husk, semolina) are skipped. History kept from 2023-01.
"""
import ast, json, os, sys

SRC = sys.argv[1]
REGIONS = [  # siat_id, source_id, region_id, file name part
    (3771, "andijan_market", "andijan", "andijan"),
    (3772, "bukhara_market", "bukhara", "bukhara"),
    (3774, "kashkadarya_market", "kashkadarya", "kashkadarya"),
    (3776, "namangan_market", "namangan", "namangan"),
    (3777, "samarkand_market", "samarkand", "samarkand"),
    (3778, "surkhandarya_market", "surkhandarya", "surkhandarya"),
    (3779, "sirdarya_market", "sirdarya", "sirdarya"),
    (3783, "khorezm_market", "khorezm", "khorezm"),
]
FIRST = "2023-M01"

# the product table from build.py (English name as in the source -> product_id), read without running build.py
tree = ast.parse(open("scripts/build.py").read())
PRODUCTS = next(ast.literal_eval(n.value) for n in tree.body if isinstance(n, ast.Assign) and getattr(n.targets[0], "id", "") == "PRODUCTS")

def q(s): return "'" + str(s).replace("'", "''") + "'"
sql = ["-- generated by data/scripts/add_regions.py: 8 more regions from stat.uz (SIAT), prices as published"]
for siat, source_id, region_id, part in REGIONS:
    d = json.load(open(os.path.join(SRC, f"sdmx_data_{siat}.json"), encoding="utf-8-sig"))[0]
    meta = {m["name_en"]: m.get("value_en") for m in d["metadata"]}
    title, note = meta["Indicator name"], meta.get("Note") or ""
    months = [k for k in d["data"][0] if k[:4].isdigit() and k >= FIRST]
    rows, skipped = {}, []
    for r in d["data"]:
        name = r["Klassifikator_en"].strip()
        if name not in PRODUCTS: skipped.append(name); continue
        rows[name] = [int(float(r[m])) if r.get(m) not in (None, "") and float(r[m]) > 0 else 0 for m in months]
    # last month = last column where at least one product has a price
    last = max(i for i in range(len(months)) if any(v[i] for v in rows.values()))
    months = months[: last + 1]
    missing = [n for n in PRODUCTS if n not in rows]
    with open(f"raw/{siat}_{part}_markets.txt", "w") as f:
        f.write(f"product|{months[0]}..{months[-1]}\n")
        for name, vals in rows.items(): f.write(f"{name}|{','.join(str(v) for v in vals[: last + 1])}\n")
    outlet = "dehqon bozori and shops (per source note)" if "shops" in note.lower() else "dehqon bozori (farmers' markets)"
    to_date = lambda m: f"{m[:4]}-{m[6:8]}-01"
    sql.append(f"insert into sources (source_id, siat_id, title, region_id, outlet_type, first_month, last_month, url) values "
               f"({q(source_id)}, {siat}, {q(title)}, {q(region_id)}, {q(outlet)}, {q(to_date(months[0]))}, {q(to_date(months[-1]))}, "
               f"{q(f'https://siat.stat.uz/data/{siat}/?lang=en')}) on conflict (source_id) do nothing;")
    values = [f"({q(source_id)},{q(PRODUCTS[name][0])},{q(to_date(m))},{v if v else 'null'})"
              for name, vals in rows.items() for m, v in zip(months, vals)]
    sql.append("insert into official_prices (source_id, product_id, month, price_som) values\n" + ",\n".join(values) +
               "\non conflict do nothing;")
    filled = sum(1 for vals in rows.values() for v in vals[: last + 1] if v)
    print(f"{siat} {region_id:13s} {months[0]}..{months[-1]}  products {len(rows)}  prices {filled}/{len(rows)*len(months)}"
          f"  skipped {skipped}  missing {missing}  outlet: {outlet}")
os.makedirs("out", exist_ok=True)
open("out/new_regions.sql", "w").write("\n".join(sql) + "\n")
print("wrote out/new_regions.sql", os.path.getsize("out/new_regions.sql"), "bytes")
